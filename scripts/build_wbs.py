def fmt_minutes(m):
    """分を「2時間30分」の形にする。"""
    h, mi = divmod(m, 60)
    if h and mi:
        return "%d時間%d分" % (h, mi)
    if h:
        return "%d時間" % h
    return "%d分" % mi


def last_row():
    return FIRST_DATA_ROW + len(TASKS) - 1


